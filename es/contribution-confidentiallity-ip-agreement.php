       const canvas = document.getElementById('signaturePad');
       const ctx = canvas.getContext('2d');
       let drawing = false;

       // Resize canvas for high-DPI
       function resizeCanvas() {
           const ratio = Math.max(window.devicePixelRatio || 1, 1);
           canvas.width = canvas.offsetWidth * ratio;
           canvas.height = canvas.offsetHeight * ratio;
           ctx.scale(ratio, ratio);
       }
       resizeCanvas();
       window.addEventListener('resize', resizeCanvas);

       // Drawing functions
       function startDrawing(x, y) {
           drawing = true;
           ctx.beginPath();
           ctx.moveTo(x, y);
       }

       function drawLine(x, y) {
           if (!drawing) return;
           ctx.lineWidth = 2;
           ctx.lineCap = 'round';
           ctx.strokeStyle = '#001f4d';
           ctx.lineTo(x, y);
           ctx.stroke();
           ctx.beginPath();
           ctx.moveTo(x, y);
       }

       function stopDrawing() {
           drawing = false;
       }

       // Mouse events
       canvas.addEventListener('mousedown', (e) => startDrawing(e.offsetX, e.offsetY));
       canvas.addEventListener('mousemove', (e) => drawLine(e.offsetX, e.offsetY));
       canvas.addEventListener('mouseup', stopDrawing);
       canvas.addEventListener('mouseout', stopDrawing);

       // Touch events
       canvas.addEventListener('touchstart', (e) => {
           e.preventDefault();
           const rect = canvas.getBoundingClientRect();
           const touch = e.touches[0];
           startDrawing(touch.clientX - rect.left, touch.clientY - rect.top);
       });
       canvas.addEventListener('touchmove', (e) => {
           e.preventDefault();
           const rect = canvas.getBoundingClientRect();
           const touch = e.touches[0];
           drawLine(touch.clientX - rect.left, touch.clientY - rect.top);
       });
       canvas.addEventListener('touchend', (e) => {
           e.preventDefault();
           stopDrawing();
       });

       // Clear button
       document.getElementById('clearBtn').addEventListener('click', () => {
           ctx.clearRect(0, 0, canvas.width, canvas.height);
       });

       // Form submission with flattened JPEG
       document.getElementById('agreementForm').addEventListener('submit', function(e) {
           // Flatten canvas to white background
           const tempCanvas = document.createElement('canvas');
           tempCanvas.width = canvas.width;
           tempCanvas.height = canvas.height;
           const tempCtx = tempCanvas.getContext('2d');
           tempCtx.fillStyle = "#ffffff";
           tempCtx.fillRect(0, 0, tempCanvas.width, tempCanvas.height);
           tempCtx.drawImage(canvas, 0, 0);

           const signatureData = tempCanvas.toDataURL('image/jpeg', 1.0);

           // Check if signature is empty
           const blankCanvas = document.createElement('canvas');
           blankCanvas.width = canvas.width;
           blankCanvas.height = canvas.height;
           const blankData = blankCanvas.toDataURL('image/jpeg', 1.0);
           if (signatureData === blankData) {
               e.preventDefault();
               alert('Please provide a signature.');
               return;
           }

           // Append hidden input
           let input = document.createElement('input');
           input.type = 'hidden';
           input.name = 'signature';
           input.value = signatureData;
           this.appendChild(input);
       });
       document.getElementById('resetBtn').addEventListener('click', () => {
           ctx.clearRect(0, 0, canvas.width, canvas.height);
           updatePreview();
       });
